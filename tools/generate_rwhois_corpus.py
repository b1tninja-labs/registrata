def write_case(case: dict, subdir: str) -> dict:
    entry = {
        "id": case["id"],
        "file": f"{subdir}/{case['id']}.txt",
        "kind": case.get("kind", "valid"),
        "parser": case["parser"],
        "recorded": False,
        "source": case.get("note", SYNTH),
        "expect": case["expect"],
        "abnf": sorted(case.get("abnf", [])),
    }
    if "roundtrip" in case:
        entry["roundtrip"] = case["roundtrip"]
    path = ROOT / subdir / f"{case['id']}.txt"
    path.parent.mkdir(parents=True, exist_ok=True)
    if "raw" in case:
        path.write_bytes(case["raw"].encode("latin-1"))
    else:
        path.write_bytes(("\r\n".join(case["lines"]) + "\r\n").encode("latin-1"))
    return entry


def main() -> int:
    # Fail before touching the tree if the generator can no longer prove what it emits.
    for problem in selfcheck():
        raise SystemExit(f"ABNF generator selfcheck failed: {problem}")
    if ROOT.exists():
        for stale in ROOT.rglob("*"):
            if stale.is_file():
                stale.unlink()
    cases = []
    for group, subdir in ((VALID, "valid"), (MALFORMED, "malformed"), (WIRE, "wire")):
        for case in group:
            claims = LEGACY_ABNF.get(case["id"])
            if claims is None:
                raise SystemExit(f"{case['id']}: no ABNF claims recorded for it")
            validate_claims(case["id"], claims, transcript_text(case))
            cases.append(write_case({**case, "abnf": claims}, subdir))
    derived = generate_cases()
    for case in derived:
        validate_case(case)
        if case.get("kind", "valid") not in _SUBDIRS:
            raise SystemExit(f"{case['id']}: unknown kind {case.get('kind')!r}")
        cases.append(write_case(case, _SUBDIRS[case.get("kind", "valid")]))
    ids = [entry["id"] for entry in cases]
    if len(set(ids)) != len(ids):
        duplicates = sorted({name for name in ids if ids.count(name) > 1})
        raise SystemExit(f"duplicate case ids: {duplicates}")
    manifest = {
        "version": 1,
        "description": (
            "RFC 2167 RWhois transcript corpus. Valid cases assert parsed structure and,"
            " where marked, parser round-trips. Malformed cases pin the failure contract:"
            " only registrata.errors.RwhoisError subclasses may escape. Every entry lists"
            ' the ABNF productions its transcript exercises under "abnf".'
        ),
        "encoding": "latin-1, crlf terminated (RFC 2167 section 3.1.9)",
        "cases": cases,
    }
    (ROOT / "manifest.json").write_text(
        json.dumps(manifest, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
        newline="\n",
    )
    kinds = [case.get("kind", "valid") for case in cases]
    print(
        f"valid={kinds.count('valid')} malformed={kinds.count('malformed')}"
        f" wire={kinds.count('wire')} derived={len(derived)} total={len(cases)}"
    )
    for line in coverage_report(cases):
        print(line)
    for name, reason in sorted(UNCOVERABLE.items()):
        print(f"documented gap {name}: {reason}")
    gaps = unexpected_gaps(cases)
    for name, reason in sorted(gaps.items()):
        print(f"UNCOVERED {name}: {reason}")
    if gaps:
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
