"""Generate the RFC 2167 fixture corpus under tests/fixtures/rwhois/.

Run ``python tools/generate_rwhois_corpus.py`` to rebuild the corpus after adding a
case; ``tests/test_rwhois_corpus.py`` reads ``manifest.json`` and fails when a
transcript and the manifest drift apart.

Transcripts are written CRLF-terminated and latin-1 encoded because RFC 2167
section 3.1.9 defines an 8-bit protocol over crlf-terminated lines; the corpus is read
back as raw bytes so parsers see what a socket would deliver.

Cases are synthesized to match the RFC 2167 grammar and several lines are quoted
verbatim from RFC 2167 examples. None is a live capture, so the manifest marks every
case "recorded": false; real recordings can be dropped in later as "recorded": true.

Two populations share the corpus. The hand-written transcripts below are the original
45 and are regenerated byte-for-byte: their ids, files, bytes and manifest keys are
unchanged, and the only thing added to their entries is ``abnf``. The second population
comes from ``rwhois_abnf_gen``, which derives a case per grammar production, checks every
artifact against ``rwhois_abnf_match`` before writing it, and records for each claimed
production the substring of the transcript that instantiates it. Derived cases are
prefixed ``abnf-`` so a reader and the coverage gate can tell them apart.
"""

