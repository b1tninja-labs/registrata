"""A real, deliberately hostile server, driven through the real client.

Everything else in this repo that fuzzes the parser hands it a list of strings. That leaves
the client's transport unexercised: the socket, ``LineReader``'s per-line ceiling, the
response line and byte budgets, and what happens when a peer stops answering mid-response.
Those are the parts that face the network, and a bug in them is reached by a server, not by a
caller's mistake.

A scripted server on loopback is the smallest fixture that reaches all of it. Payloads are
generated by the grammar fuzzer and spliced, so the bytes arriving are not only the ones
someone thought to write down here.

Every test bounds time with a socket timeout and asserts that a timeout is *possible* to
distinguish from a hang: the property under attack is that a client never waits forever and
never leaks a builtin.
"""

from __future__ import annotations

import random
import socket
import struct
import sys
import threading

import pytest

sys.path.insert(
    0, str(__import__("pathlib").Path(__file__).resolve().parents[1] / "tests")
)

from registrata.client import RwhoisClient  # noqa: E402
from registrata.errors import RwhoisError  # noqa: E402
from test_rwhois_property import generated_artifacts, splice  # noqa: E402

BANNER = b"%rwhois V-1.5:000000:00 hostile.example.net (adversary)\r\n"
ACCEPT_TIMEOUT = 5.0
# Short enough that a client which cannot hang is still a fast test.
CLIENT_TIMEOUT = 2.0


def _answer_negotiation(conn: socket.socket) -> bool:
    """Reply ``%ok`` if the first thing the client sends is ``-holdconnect on``; True if it was.

    ``RwhoisClient`` negotiates a held session at connect time, because RFC 2167 section 3.3.5
    makes ``off`` the default for every connection. Every script in this file models the answer to
    a *query*, so the negotiation has to be consumed first; leaving it would hand the hostile
    payload to the negotiation and send the real query into a socket the server has closed.
    """
    try:
        request = conn.recv(4096)
    except OSError:
        return False
    if b"-holdconnect" in request:
        try:
            conn.sendall(b"%ok\r\n")
        except OSError:
            pass
        return True
    return False


def serve(
    payload: bytes,
    *,
    read_request: bool = True,
    send_banner: bool = True,
    recv_timeout: float = ACCEPT_TIMEOUT,
    rst: bool = True,
):
    """Accept one connection, optionally read a request, write ``payload``, then close.

    ``read_request`` waits for the client to speak first, which is what a real server does; a
    client that fails while reading the banner never sends anything, so scripts that expect a
    connect-time failure must pass ``read_request=False`` or the exchange deadlocks until the
    socket timeout. ``rst=False`` closes gracefully, letting queued bytes drain instead of
    discarding them -- the harsher RST is the default because that is what a hostile peer does.

    Returns (listener, thread, done). Callers must tear all three down; the listener holds an
    ephemeral port and a live accept loop until closed.
    """
    listener = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
    listener.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
    listener.bind(("127.0.0.1", 0))
    listener.listen(1)
    listener.settimeout(ACCEPT_TIMEOUT)
    done = threading.Event()

    def serve_one() -> None:
        try:
            conn, _peer = listener.accept()
        except OSError:
            done.set()
            return
        try:
            if send_banner:
                conn.sendall(BANNER)
            if read_request:
                conn.settimeout(recv_timeout)
                if _answer_negotiation(conn):
                    # The negotiation is not the request this script is answering.
                    try:
                        conn.recv(4096)
                    except OSError:
                        pass
            if payload:
                try:
                    conn.sendall(payload)
                except OSError:
                    pass
        finally:
            # linger=0 turns the close into an RST, which is the harsher thing a peer can do
            # and the case a tolerant reader has to survive.
            if rst:
                try:
                    conn.setsockopt(
                        socket.SOL_SOCKET, socket.SO_LINGER, struct.pack("ii", 1, 0)
                    )
                except OSError:
                    pass
            conn.close()
            done.set()

    thread = threading.Thread(target=serve_one, daemon=True)
    thread.start()
    return listener, thread, done


def with_client(listener, thread, done, call, **client_kwargs):
    """Run ``call(client)`` against a scripted server, then tear the server down cleanly."""
    host, port = listener.getsockname()
    try:
        client = RwhoisClient.connect(
            host, port, timeout=CLIENT_TIMEOUT, **client_kwargs
        )
        try:
            return call(client)
        finally:
            client.close()
    finally:
        done.wait(ACCEPT_TIMEOUT)
        thread.join(ACCEPT_TIMEOUT)
        listener.close()


# ----------------------------------------------------------------- generative --------


@pytest.mark.parametrize("seed", range(12))
def test_spliced_server_output_never_escapes_as_a_builtin(seed: int) -> None:
    """The documented exception contract, enforced over a socket this time.

    The parser-level version of this test lives in ``test_rwhois_property.py``; the gap it
    cannot cover is that ``RwhoisClient`` wraps the parser in its own read loop, and a
    ``ConnectionError`` raised mid-parse, or a ``UnicodeDecodeError`` from the latin-1 decode
    inside ``LineReader``, would surface there and nowhere else.
    """
    rng = random.Random(f"registrata-property:hostile:{seed}")
    problems: list[str] = []

    for _kind, artifact in generated_artifacts(seed):
        hostile = splice(rng, artifact)
        payload = f"{hostile}\r\n%ok\r\n".encode("latin-1", errors="replace")

        def ask(client: RwhoisClient, *, hostile=hostile) -> str:
            try:
                client.query("domain", "vogon", raise_errors=False)
            except RwhoisError as exc:
                return f"typed:{type(exc).__name__}"
            except ConnectionError as exc:
                # A peer that hangs up is a protocol-level fact, reported as ConnectionError.
                return f"closed:{type(exc).__name__}"
            except Exception as exc:  # noqa: BLE001 - the type escaping is the assertion
                return f"BUILTIN:{type(exc).__name__}:{exc}"
            return "ok"

        listener, thread, done = serve(payload)
        try:
            outcome = with_client(listener, thread, done, ask)
        except (ConnectionError, TimeoutError) as exc:
            outcome = f"closed:{type(exc).__name__}"
        except Exception as exc:  # noqa: BLE001
            outcome = f"BUILTIN:{type(exc).__name__}:{exc}"
        finally:
            listener.close()

        if outcome.startswith("BUILTIN"):
            problems.append(f"{_kind} splice {hostile!r} -> {outcome}")

    assert not problems, "\n".join(problems)


# --------------------------------------------------------------- scripted attacks ----


def test_a_response_that_never_terminates_is_reported_not_waited_on() -> None:
    """A peer that stops talking and closes must yield an incomplete result, not a hang.

    Closed gracefully here, because the assertion is about the *content* of the outcome: the
    bytes have to arrive for "the client saw a response with no terminator" to mean anything.
    The harsher reset variant below asserts the weaker property that an RST can support.
    """
    payload = b"domain:Domain-Name:partial\r\ndomain:ID:partial.example.com\r\n"

    def ask(client: RwhoisClient):
        return client.query("domain", "vogon", raise_errors=False)

    listener, thread, done = serve(payload, rst=False)
    result = with_client(listener, thread, done, ask)

    assert result.ok is False, "a response with no %ok must not be reported as complete"


def test_a_response_reset_midway_is_never_reported_as_complete() -> None:
    """A peer that resets mid-response may deliver nothing, but must never look finished.

    An RST can discard a queue the peer has not read, so the honest assertion is narrow:
    either the client reports an incomplete response or it reports that the connection died.
    Reporting ``ok`` is the one outcome that would corrupt a caller's data, and that is what
    this forbids.
    """
    payload = b"domain:Domain-Name:partial\r\ndomain:ID:partial.example.com\r\n"

    def ask(client: RwhoisClient) -> bool:
        try:
            return client.query("domain", "vogon", raise_errors=False).ok
        except ConnectionError:
            return False

    listener, thread, done = serve(payload)
    reported_ok = with_client(listener, thread, done, ask)

    assert reported_ok is False


def test_an_oversized_line_is_refused_rather_than_buffered() -> None:
    """The per-line ceiling exists so one line cannot exhaust memory before it is parsed."""
    payload = b"domain:Domain-Name:" + b"x" * 4096 + b"\r\n%ok\r\n"

    def ask(client: RwhoisClient):
        try:
            client.query("domain", "vogon", raise_errors=False)
        except RwhoisError as exc:
            return exc
        return None

    listener, thread, done = serve(payload, rst=False)
    outcome = with_client(listener, thread, done, ask, max_line_bytes=1024)

    assert isinstance(outcome, RwhoisError), f"expected a refusal, got {outcome!r}"


def test_a_flood_stops_at_the_response_budget() -> None:
    """Line and byte budgets are enforced against a server that simply never stops talking.

    Closed gracefully: this asserts on bytes that have to arrive, and an RST can discard a
    peer's unread queue, which turns a deterministic assertion into a coin flip. The
    RST-drops-data case is covered by the truncation test, whose assertion tolerates it.
    """
    payload = (
        b"".join(
            b"domain:Domain-Name:flood-line-%05d\r\n" % index for index in range(5000)
        )
        + b"%ok\r\n"
    )

    def ask(client: RwhoisClient):
        try:
            client.query("domain", "vogon", raise_errors=False)
        except RwhoisError as exc:
            return exc
        return None

    listener, thread, done = serve(payload, rst=False)
    lines_outcome = with_client(listener, thread, done, ask, max_response_lines=50)
    assert isinstance(lines_outcome, RwhoisError), "the line budget did not fire"

    listener, thread, done = serve(payload, rst=False)
    bytes_outcome = with_client(listener, thread, done, ask, max_response_bytes=4096)
    assert isinstance(bytes_outcome, RwhoisError), "the byte budget did not fire"


def test_a_server_that_says_nothing_times_out_instead_of_hanging() -> None:
    """The worst denial of service is silence, and the client has a bound on it.

    CLIENT_TIMEOUT is what makes this finite; the assertion is that the wait ends in an
    error of a recognised kind rather than never.
    """
    listener, thread, done = serve(b"", read_request=False, send_banner=False)

    with pytest.raises((TimeoutError, ConnectionError, socket.timeout)):
        with_client(
            listener, thread, done, lambda client: client.query("domain", "vogon")
        )


def test_a_first_line_that_is_not_a_banner_is_refused_at_connect() -> None:
    """The banner is parsed before the caller can reach the socket.

    An implementation that stored a half-parsed banner would hand every later response a
    desynchronised stream, since the banner line would then be read as data.
    """
    listener, thread, done = serve(
        b"this is not a banner\r\n",
        send_banner=False,
        read_request=False,
        rst=False,
    )

    with pytest.raises(RwhoisError):
        with_client(
            listener, thread, done, lambda client: client.query("domain", "vogon")
        )


@pytest.mark.parametrize(
    "noise",
    [
        b"\x00" * 256 + b"\r\n%ok\r\n",
        b"\xff\xfe\xfd" * 100 + b"\r\n%ok\r\n",
        b"\r\n" * 500 + b"%ok\r\n",
        b"%ok\r\n" * 200,
        b"\x1b[31mred\x1b[0m\r\n%ok\r\n",
    ],
    ids=["nul", "high-octets", "blank-flood", "ok-flood", "ansi"],
)
def test_binary_noise_on_the_wire_is_survivable(noise: bytes) -> None:
    """Nothing a server can send may take the client down with a builtin.

    NUL is outside ``any-char`` and high octets are inside it, but neither distinction should
    be reachable as a ``UnicodeDecodeError`` or an ``IndexError`` in the caller's process: the
    latin-1 decode is total over a byte stream, and the parser is expected to convert junk into
    either a typed error or a result it can explain.
    """

    def ask(client: RwhoisClient) -> str:
        try:
            client.query("domain", "vogon", raise_errors=False)
        except (RwhoisError, ConnectionError) as exc:
            return type(exc).__name__
        except Exception as exc:  # noqa: BLE001 - the escaping type is the assertion
            pytest.fail(f"builtin escaped over the wire: {type(exc).__name__}: {exc}")
        return "ok"

    listener, thread, done = serve(noise)
    with_client(listener, thread, done, ask)
